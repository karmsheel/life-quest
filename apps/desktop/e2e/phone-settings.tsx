/**
 * E2E harness for Settings → Phone, driven by `phone-ui.electron.mjs`.
 *
 * A system-in-isolation rig, so the ways it can fail are written down first:
 *
 *  1. The section renders nothing: no toggle, no address, no pair control —
 *     the door exists and the operator cannot reach it.
 *  2. Saving an http address is accepted. The phone cannot install or queue
 *     offline over http, so the panel must refuse it and say why.
 *  3. Pair is offered without an address, minting a code no phone can redeem.
 *  4. The pair panel shows no code, no QR, or a QR that is not an image the
 *     browser can decode; or Cancel leaves it on screen.
 *  5. The countdown never moves, so a five-minute code looks permanent.
 *  6. The metric select writes nothing or the wrong id, or the panel presents
 *     the phone as a ledger browser.
 *  7. A paired device cannot be forgotten, or Forget leaves the row.
 *
 * The IPC bridge is stubbed (a dev-server page has no preload); the settings
 * section, the real CSS, and the real layout engine are shipping code. The
 * pairing payload the stub returns is generated by the rig with the same
 * `qrcode` call the service uses, so the QR on screen is a real QR.
 */
import { StrictMode, useEffect } from "react";
import { createRoot } from "react-dom/client";
import { SettingsPhone } from "@/components/settings/SettingsPhone";
import { ThemeProvider } from "@/components/theme/ThemeProvider";
import { VaultProvider } from "@/state/VaultProvider";
import "@/styles/global.css";

const ok = <T,>(value: T) => Promise.resolve({ ok: true as const, value });

const SNAPSHOT = {
  rootPath: "C:/harness-vault",
  lifequest: {
    schemaVersion: 1 as const,
    id: "harness-vault",
    name: "Harness Vault",
    createdAt: "2026-01-01T00:00:00.000Z",
  },
  settings: {
    hermesBaseUrl: "http://127.0.0.1:1",
    theme: "dark" as const,
    weekStartDay: "monday" as const,
  },
  domains: [],
  agents: [],
  decisions: [],
  log: [],
  map: null,
  mapError: null,
  goals: [],
  goalsError: null,
  reviews: [],
  planning: [],
  weeklyFileCount: 0,
};

type PhoneMetric = "net_worth" | "month_spend" | "month_income" | null;

type PhoneState = {
  enabled: boolean;
  doorUrl: string;
  publicOrigin: string | null;
  error: string | null;
  devices: Array<{ id: string; name: string; createdAt: string; lastSeenAt: string }>;
  metric: PhoneMetric;
  pendingDrafts: Array<{
    clientId: string;
    text: string;
    captureDate: string;
    deviceName: string;
  }>;
};

type Pairing = {
  code: string;
  link: string;
  qrDataUrl: string;
  expiresAt: string;
};

type Rig = { state: PhoneState; pairing: Pairing | null };

function readRig(): Rig {
  const raw = new URLSearchParams(window.location.search).get("rig");
  if (!raw) throw new Error("phone settings harness: the rig param is missing");
  return JSON.parse(raw) as Rig;
}

const rig = readRig();
let current: PhoneState = rig.state;
const calls: Array<Record<string, unknown>> = [];
(window as unknown as { __lqPhoneCalls: unknown }).__lqPhoneCalls = calls;

const bridge: Record<string, unknown> = {
  vaultGetSnapshot: () => ok(SNAPSHOT),
  vaultListRecent: () => Promise.resolve([]),
  onVaultFileChanged: () => () => {},
  // ThemeProvider reads the profile's theme files at mount and subscribes for
  // writes from the companion. The generic `ok(null)` fallback is wrong for
  // these: `themesList` is iterated, and `onThemesChanged` must hand back an
  // unsubscribe the effect calls on cleanup — a Promise there throws in the
  // StrictMode cleanup and React unmounts the page.
  themesList: () => ok([]),
  themeGetState: () => ok({ keptFile: null }),
  onThemesChanged: () => () => {},
  phone: {
    state: () => Promise.resolve(current),
    setEnabled: (enabled: boolean) => {
      calls.push({ method: "setEnabled", enabled });
      current = { ...current, enabled };
      return Promise.resolve(current);
    },
    setPublicOrigin: (origin: string) => {
      calls.push({ method: "setPublicOrigin", origin });
      if (!/^https:\/\//.test(origin)) {
        return Promise.resolve({
          ok: false,
          error: "Enter an https address with no path, e.g. https://studio.tailnet.ts.net",
        });
      }
      current = { ...current, publicOrigin: origin, error: null };
      return Promise.resolve({ ok: true, value: current });
    },
    setMetric: (metric: PhoneMetric) => {
      calls.push({ method: "setMetric", metric });
      current = { ...current, metric };
      return Promise.resolve({ ok: true, value: { schemaVersion: 1, metric } });
    },
    pairingStart: () => {
      calls.push({ method: "pairingStart" });
      return rig.pairing
        ? Promise.resolve({ ok: true, value: rig.pairing })
        : Promise.resolve({ ok: false, error: "Phone access is off" });
    },
    pairingCancel: () => {
      calls.push({ method: "pairingCancel" });
      return Promise.resolve();
    },
    revokeDevice: (id: string) => {
      calls.push({ method: "revokeDevice", id });
      current = {
        ...current,
        devices: current.devices.filter((device) => device.id !== id),
      };
      return Promise.resolve({ ok: true, value: current });
    },
    queue: () => Promise.resolve({ drafts: [], count: 0 }),
    onChanged: () => () => {},
  },
  windowChrome: {
    get: () => Promise.resolve({ overlay: true, platform: "win32" }),
    setTitleBarOverlay: () => Promise.resolve(),
    minimize: () => {},
    toggleMaximize: () => {},
    close: () => {},
    isMaximized: () => Promise.resolve(false),
    onMaximizeChange: () => () => {},
  },
};

const stubbed = new Proxy(bridge, {
  get(target, prop) {
    const found = target[prop as string];
    if (found !== undefined) return found;
    return () => ok(null);
  },
  has: () => true,
});

(window as unknown as { lifequest: unknown }).lifequest = stubbed;

function Harness() {
  useEffect(() => {
    (window as unknown as { phoneHarnessCalls: unknown }).phoneHarnessCalls = () => calls;
  }, []);
  return <SettingsPhone />;
}

const root = document.getElementById("root");
if (!root) throw new Error("#root missing from phone-settings.html");

createRoot(root).render(
  <StrictMode>
    <ThemeProvider>
      <VaultProvider>
        <div className="app-root">
          <div className="app-root__body">
            <div className="shell">
              <main className="shell__main">
                <div className="shell__content">
                  <Harness />
                </div>
              </main>
            </div>
          </div>
        </div>
      </VaultProvider>
    </ThemeProvider>
  </StrictMode>,
);

let settle: () => void = () => {};
const ready = new Promise<void>((resolve) => {
  settle = resolve;
});

const waitForPage = () => {
  const heading = document.querySelector(".settings-panel__title");
  const toggle = document.querySelector('[role="switch"][aria-label="Phone access"]');
  if (!heading || heading.textContent !== "Phone" || !toggle) {
    requestAnimationFrame(waitForPage);
    return;
  }
  requestAnimationFrame(() => requestAnimationFrame(() => settle()));
};
requestAnimationFrame(waitForPage);

(window as unknown as { phoneSettingsHarnessReady: Promise<void> }).phoneSettingsHarnessReady =
  ready;
